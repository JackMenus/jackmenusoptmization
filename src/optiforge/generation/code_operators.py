"""Executable (Python source) operator candidates.

Two ways such sources arise:

* :class:`CodeTemplateGenerator` - an offline generator that composes Python
  source for a mutation operator from a grammar of code fragments (coordinate
  selection x step distribution x scale rule x boundary rule x integer rule x
  discrete moves).  Some combinations are deliberately allowed to be wrong
  (e.g. no boundary handling); the validation gates must catch them.
* an optional language-model provider (see :mod:`.providers`).

Either way the source is untrusted.  It is executed only inside
:class:`~optiforge.isolation.sandbox.SandboxProcess` and only after the
isolation probe passed.  Contract::

    def mutate(x: list[float], info: dict, rng: random.Random) -> list[float]

``info`` holds ``lower``, ``upper``, ``types`` (per position: real, integer,
binary, categorical, permutation), ``perm_blocks`` ([start, stop] pairs),
``sigma`` (current adaptive step multiplier times the base step) and ``dim``.
"""
from __future__ import annotations

import math
import textwrap

import numpy as np

from ..core.errors import CandidateRejected, IsolationUnavailable
from ..isolation.sandbox import SandboxConfig, SandboxProcess, probe

TYPE_NAMES = {0: "real", 1: "integer", 2: "binary", 3: "categorical", 4: "permutation"}

CHOICES = {
    "select": ["all", "rate", "one"],
    "dist": ["gauss", "cauchy", "uniform", "laplace"],
    "scale": ["sigma_range", "bound_distance"],
    "boundary": ["clip", "reflect", "none"],
    "integer": ["round", "stochastic_round", "none"],
    "discrete": ["resample", "keep"],
    "perm": ["swap", "reverse", "keep"],
}


def render_mutation(g: dict) -> str:
    """Render Python source for one point of the code-template grammar."""
    sel = {
        "all": "idx = [i for i in range(n) if types[i] in ('real', 'integer')]",
        "rate": f"idx = [i for i in range(n) if types[i] in ('real', 'integer') and rng.random() < {g.get('rate', 0.3)!r}]\n"
                "    if not idx:\n"
                "        cand = [i for i in range(n) if types[i] in ('real', 'integer')]\n"
                "        idx = [rng.choice(cand)] if cand else []",
        "one": "cand = [i for i in range(n) if types[i] in ('real', 'integer')]\n    idx = [rng.choice(cand)] if cand else []",
    }[g["select"]]
    draw = {
        "gauss": "rng.gauss(0.0, 1.0)",
        "cauchy": "max(-20.0, min(20.0, math.tan(math.pi * (rng.random() - 0.5))))",
        "uniform": "rng.uniform(-1.7320508, 1.7320508)",
        "laplace": "(rng.expovariate(1.0) - rng.expovariate(1.0)) / 1.4142136",
    }[g["dist"]]
    scale = {
        "sigma_range": "info['sigma'] * (hi[i] - lo[i])",
        "bound_distance": "info['sigma'] * 2.0 * max(min(y[i] - lo[i], hi[i] - y[i]), 0.05 * (hi[i] - lo[i]))",
    }[g["scale"]]
    boundary = {
        "clip": "v = min(max(v, lo[i]), hi[i])",
        "reflect": ("w = hi[i] - lo[i]\n"
                    "        if w > 0:\n"
                    "            r = (v - lo[i]) % (2.0 * w)\n"
                    "            v = lo[i] + (2.0 * w - r if r > w else r)"),
        "none": "pass",
    }[g["boundary"]]
    integer = {
        "round": "if types[i] == 'integer':\n            v = float(round(v))",
        "stochastic_round": ("if types[i] == 'integer':\n"
                             "            f = math.floor(v)\n"
                             "            v = float(f + (1 if rng.random() < v - f else 0))"),
        "none": "pass",
    }[g["integer"]]
    if g["integer"] != "none" and g["boundary"] != "none":
        # rounding can step past a bound only if bounds are not integral; re-clip to be safe
        integer += "\n        v = min(max(v, lo[i]), hi[i])"
    discrete = {
        "resample": (f"for i in range(n):\n"
                     f"        if types[i] == 'binary' and rng.random() < {g.get('p_discrete', 0.1)!r}:\n"
                     f"            y[i] = 1.0 - y[i]\n"
                     f"        elif types[i] == 'categorical' and rng.random() < {g.get('p_discrete', 0.1)!r}:\n"
                     f"            k = int(hi[i]) + 1\n"
                     f"            if k > 1:\n"
                     f"                y[i] = float((int(y[i]) + rng.randrange(1, k)) % k)"),
        "keep": "pass",
    }[g["discrete"]]
    perm = {
        "swap": ("for a, b in info['perm_blocks']:\n"
                 "        if b - a >= 2:\n"
                 "            i, j = rng.sample(range(a, b), 2)\n"
                 "            y[i], y[j] = y[j], y[i]"),
        "reverse": ("for a, b in info['perm_blocks']:\n"
                    "        if b - a >= 2:\n"
                    "            i, j = sorted(rng.sample(range(a, b), 2))\n"
                    "            y[i:j + 1] = y[i:j + 1][::-1]"),
        "keep": "pass",
    }[g["perm"]]
    src = f'''
# generated by optiforge CodeTemplateGenerator: {sorted(g.items())}
def mutate(x, info, rng):
    lo, hi, types = info["lower"], info["upper"], info["types"]
    n = len(x)
    y = list(x)
    {sel}
    for i in idx:
        v = y[i] + {draw} * {scale}
        {boundary}
        {integer}
        y[i] = v
    {discrete}
    {perm}
    return y
'''
    return textwrap.dedent(src).lstrip()


class CodeTemplateGenerator:
    """Random/evolutionary search over the code-fragment grammar."""

    def sample(self, rng: np.random.Generator) -> dict:
        g = {k: str(rng.choice(v)) for k, v in CHOICES.items()}
        g["rate"] = float(np.round(rng.uniform(0.1, 0.6), 2))
        g["p_discrete"] = float(np.round(rng.uniform(0.02, 0.3), 2))
        return g

    def mutate(self, g: dict, rng: np.random.Generator) -> dict:
        g = dict(g)
        k = str(rng.choice(list(CHOICES) + ["rate", "p_discrete"]))
        if k in CHOICES:
            g[k] = str(rng.choice([c for c in CHOICES[k] if c != g[k]] or CHOICES[k]))
        elif k == "rate":
            g[k] = float(np.clip(np.round(g[k] * np.exp(rng.normal(0, 0.4)), 2), 0.05, 0.9))
        else:
            g[k] = float(np.clip(np.round(g[k] * np.exp(rng.normal(0, 0.4)), 2), 0.01, 0.5))
        return g

    @staticmethod
    def types_changed(g: dict) -> list[str]:
        t = ["real", "integer"]
        if g["discrete"] != "keep":
            t += ["binary", "categorical"]
        if g["perm"] != "keep":
            t.append("permutation")
        return t


def space_info(space, sigma: float) -> dict:
    return {
        "lower": space.lower.tolist(), "upper": space.upper.tolist(),
        "types": [TYPE_NAMES[int(c)] for c in space.codes], "perm_blocks": [[s.start, s.stop] for s in space.perm_blocks],
        "sigma": float(sigma), "dim": int(space.dim),
    }


class SandboxedCodeOperator:
    """Transformer backed by an isolated worker running candidate source code."""

    MAX_RESTARTS = 3

    def __init__(self, cid: str, source: str, types: list[str], version: str = "1", base_sigma: float = 0.1,
                 config: SandboxConfig | None = None) -> None:
        rep = probe()
        if not rep.available:
            raise IsolationUnavailable(f"arbitrary generated-code execution is disabled: {rep.reason}")
        self.cid, self.source, self.types, self.version = cid, source, list(types), version
        self.base_sigma = base_sigma
        self.config = config or SandboxConfig()
        self._proc: SandboxProcess | None = None
        self._info_cache = None
        self.stats = {"calls": 0, "invalid_outputs": 0, "raw_domain_violations": 0, "failures": 0, "starts": 0}

    def _ensure(self) -> SandboxProcess:
        if self._proc is None or self._proc.proc.poll() is not None:
            # each worker gets a fresh CPU rlimit, so restarts are capped rather than unbounded
            if self.stats["starts"] > self.MAX_RESTARTS:
                raise CandidateRejected(f"code operator {self.cid}: sandbox worker restarted {self.MAX_RESTARTS} times; "
                                        "candidate disabled")
            self.stats["starts"] += 1
            self._proc = SandboxProcess(self.source, "mutate", self.config)
        return self._proc

    def transform(self, x: np.ndarray, space, rng: np.random.Generator, mult: float, ctx=None) -> np.ndarray:
        info = space_info(space, self.base_sigma * mult)
        self.stats["calls"] += 1
        try:
            resp = self._ensure().call([float(v) for v in x], info, int(rng.integers(2**31 - 1)))
        except Exception as exc:
            self.stats["failures"] += 1
            if self._proc is not None:
                self._proc.close()
            self._proc = None
            raise CandidateRejected(f"code operator {self.cid} failed in sandbox: {exc}") from exc
        if not resp.get("ok"):
            self.stats["failures"] += 1
            raise CandidateRejected(f"code operator {self.cid} raised: {resp.get('error')}")
        y = np.asarray(resp.get("y", []), dtype=float)
        if y.shape != x.shape or not np.all(np.isfinite(y)):
            self.stats["invalid_outputs"] += 1
            if ctx is not None:
                ctx.diagnostics["code_invalid_outputs"] = self.stats["invalid_outputs"]
            return np.array(x, dtype=float, copy=True)
        if not space.contains(y):
            self.stats["raw_domain_violations"] += 1
            if ctx is not None:
                ctx.diagnostics["code_raw_domain_violations"] = self.stats["raw_domain_violations"]
        return y

    def close(self) -> None:
        if self._proc is not None:
            self._proc.close()
            self._proc = None
